import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {competitiveFare,competitiveModel,applyCompetitiveTariffs,tariffVersion} from '../src/competitive-tariffs.js';
import {defaultFare,validFare,holidayInfo,performanceChoice,quote,visitQuote,prepaymentForVisit,prices} from '../docs/fares.js';
test('competitive tariff grid, preserved settings and capped advance',()=>{
 const old={...defaultFare,km:{...defaultFare.km,Near:30,Far:31},prepayments:{...defaultFare.prepayments,enabled:false,paymentMethod:'none',holdHours:36}};
 const f=competitiveFare(old);assert.ok(validFare(f));assert.equal(f.prepayments.enabled,false);assert.equal(f.prepayments.holdHours,36);
 assert.equal(f.prepayments.rules.Kitee.amount,2000);assert.equal(f.prepayments.rules.Near.amount,2500);assert.equal(f.prepayments.rules.Far.amount,5000);
 assert.equal(performanceChoice(f,'gift',15,'solo').amount,4500);
 assert.equal(performanceChoice(f,'home',20,'solo').amount,6000);
 assert.equal(performanceChoice(f,'home',30,'solo').amount,8000);
 assert.equal(performanceChoice(f,'home',45,'solo').amount,11000);
 assert.equal(performanceChoice(f,'home',20,'duo').amount,9500);
 assert.equal(performanceChoice(f,'home',30,'duo').amount,12000);
 assert.equal(holidayInfo('2026-12-24T16:00',f).percent,20);
 assert.equal(holidayInfo('2026-12-24T20:00',f),null);
 assert.equal(holidayInfo('2026-12-31T17:00',f).percent,10);
 assert.equal(holidayInfo('2026-12-31T21:00',f).percent,25);
 assert.equal(holidayInfo('2027-01-01T01:59',f).percent,50);
 assert.equal(holidayInfo('2027-01-01T02:00',f),null);
 assert.equal(holidayInfo('2027-01-13T19:00',f).percent,10);
 const active=competitiveFare(defaultFare);
 const q=visitQuote(quote(active,{label:'от 45 €',remote:false},'Kitee',false,['2026-12-31T23:00'],performanceChoice(active,'gift',15,'solo')),1,0);
 assert.equal(q.total,6750);assert.equal(prepaymentForVisit(active,q).amount,2000);
 assert.equal(prepaymentForVisit(active,{...q,total:1000}).amount,1000);
});
test('site price and unrelated model fields preserved',()=>{
 const m=competitiveModel({texts:{other:'keep'},cards:[{id:'v',title:'Видеопоздравление',price:'50 €'},{id:'x',title:'Дискотека',price:'200 €'}],durations:{event:'60 мин'}});
 assert.equal(m.texts.other,'keep');assert.equal(m.cards[0].price,'25 €');assert.equal(m.cards[1].price,'200 €');assert.equal(m.durations.event,'60 мин');
 assert.equal(prices(m).gift.label,'от 45 €');assert.equal(prices(m).home.label,'от 60 €');
});
test('migration writes D1-style transaction once, preserves draft and prior price snapshots',async()=>{
 const sql=new DatabaseSync(':memory:');sql.exec(readFileSync(new URL('../schema.sql',import.meta.url),'utf8'));
 const db={prepare(query){return {bind(...args){const st=sql.prepare(query);return {first:async()=>st.get(...args),execute:()=>st.run(...args)};},first:async()=>sql.prepare(query).get()};},async batch(xs){sql.exec('BEGIN');try{for(const x of xs)x.execute();sql.exec('COMMIT');}catch(e){sql.exec('ROLLBACK');throw e;}}};
 const old={...defaultFare,km:{...defaultFare.km,Custom:35}};
 sql.prepare("INSERT INTO booking_settings(key,value) VALUES('travel_fare',?)").run(JSON.stringify(old));
 sql.prepare("INSERT INTO content(key,value) VALUES('site',?)").run(JSON.stringify({giftPrice:'от 50 €',bio:'keep'}));
 const pub={texts:{'programs-9':'от 50 €'},cards:[{id:'video',title:'Видеопоздравление',price:'40 €'}]};
 sql.prepare("INSERT INTO site_revisions(body,published,created_at) VALUES(?,1,'now')").run(JSON.stringify(pub));
 sql.prepare("INSERT INTO site_revisions(body,published,created_at) VALUES(?,0,'now')").run(JSON.stringify({...pub,draftOnly:true}));
 const result=await applyCompetitiveTariffs(db);assert.equal(result.videoCards,1);assert.equal(result.alreadyApplied,false);
 const published=JSON.parse(sql.prepare('SELECT body FROM site_revisions WHERE published=1 ORDER BY id DESC LIMIT 1').get().body);
 const draft=JSON.parse(sql.prepare('SELECT body FROM site_revisions ORDER BY id DESC LIMIT 1').get().body);
 assert.equal(published.cards[0].price,'25 €');assert.equal(draft.draftOnly,true);
 assert.equal(JSON.parse(sql.prepare("SELECT value FROM content WHERE key='site'").get().value).bio,'keep');
 assert.ok(sql.prepare('SELECT value FROM booking_settings WHERE key=?').get(tariffVersion));
 assert.equal(sql.prepare('SELECT COUNT(*) n FROM site_revisions').get().n,4);
 assert.equal((await applyCompetitiveTariffs(db)).alreadyApplied,true);
 assert.equal(sql.prepare('SELECT COUNT(*) n FROM site_revisions').get().n,4);
 sql.close();
});
